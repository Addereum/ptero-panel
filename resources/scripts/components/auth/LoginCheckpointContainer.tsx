import React, { useState } from 'react';
import { Link, RouteComponentProps } from 'react-router-dom';
import loginCheckpoint from '@/api/auth/loginCheckpoint';
import LoginFormContainer from '@/components/auth/LoginFormContainer';
import { ActionCreator } from 'easy-peasy';
import { StaticContext } from 'react-router';
import { useFormikContext, withFormik } from 'formik';
import useFlash from '@/plugins/useFlash';
import { FlashStore } from '@/state/flashes';
import Field from '@/components/elements/Field';
import tw from 'twin.macro';

interface Values {
    code: string;
    recoveryCode: '';
}

type OwnProps = RouteComponentProps<Record<string, string | undefined>, StaticContext, { token?: string }>;

type Props = OwnProps & {
    clearAndAddHttpError: ActionCreator<FlashStore['clearAndAddHttpError']['payload']>;
};

const LoginCheckpointContainer = () => {
    const { isSubmitting, setFieldValue } = useFormikContext<Values>();
    const [isMissingDevice, setIsMissingDevice] = useState(false);

    return (
        <LoginFormContainer
            title={'Two-Factor Checkpoint'}
            subtitle={
                isMissingDevice
                    ? 'Enter one of your emergency recovery codes to verify your identity.'
                    : 'Enter the 6-digit verification code generated by your authenticator app.'
            }
        >
            <div css={tw`mt-4`}>
                <Field
                    name={isMissingDevice ? 'recoveryCode' : 'code'}
                    label={isMissingDevice ? 'Recovery Code' : 'Authentication Code'}
                    placeholder={isMissingDevice ? 'Enter recovery code' : '000000'}
                    type={'text'}
                    autoComplete={'one-time-code'}
                    autoFocus
                />
            </div>
            <div css={tw`mt-6`}>
                <button
                    type={'submit'}
                    disabled={isSubmitting}
                    css={[
                        tw`w-full py-3 px-4 rounded-xl font-medium text-sm text-white flex items-center justify-center transition-all duration-150 border-0 cursor-pointer`,
                        isSubmitting
                            ? tw`bg-blue-600/70 cursor-not-allowed`
                            : tw`bg-blue-600 hover:bg-blue-500 active:scale-[0.99]`,
                    ]}
                    style={{
                        boxShadow: isSubmitting ? 'none' : '0 10px 25px -5px rgba(37, 99, 235, 0.35)',
                    }}
                >
                    {isSubmitting ? (
                        <div css={tw`w-5 h-5 border-2 border-white/30 border-t-white rounded-full animate-spin`} />
                    ) : (
                        'Continue'
                    )}
                </button>
            </div>
            <div css={tw`mt-5 flex flex-col items-center gap-2.5`}>
                <button
                    type={'button'}
                    onClick={() => {
                        setFieldValue('code', '');
                        setFieldValue('recoveryCode', '');
                        setIsMissingDevice((s) => !s);
                    }}
                    css={tw`bg-transparent border-0 cursor-pointer text-xs font-medium text-neutral-400 hover:text-white transition-colors duration-150 p-0`}
                >
                    {!isMissingDevice ? "Lost your device? Use recovery code" : 'Use authenticator app code'}
                </button>
                <Link
                    to={'/auth/login'}
                    css={tw`text-xs font-medium text-neutral-500 hover:text-neutral-300 transition-colors duration-150 no-underline`}
                >
                    &larr; Return to Sign In
                </Link>
            </div>
        </LoginFormContainer>
    );
};

const EnhancedForm = withFormik<Props, Values>({
    handleSubmit: ({ code, recoveryCode }, { setSubmitting, props: { clearAndAddHttpError, location } }) => {
        loginCheckpoint(location.state?.token || '', code, recoveryCode)
            .then((response) => {
                if (response.complete) {
                    // @ts-expect-error this is valid
                    window.location = response.intended || '/';
                    return;
                }

                setSubmitting(false);
            })
            .catch((error) => {
                console.error(error);
                setSubmitting(false);
                clearAndAddHttpError({ error });
            });
    },

    mapPropsToValues: () => ({
        code: '',
        recoveryCode: '',
    }),
})(LoginCheckpointContainer);

export default ({ history, location, ...props }: OwnProps) => {
    const { clearAndAddHttpError } = useFlash();

    if (!location.state?.token) {
        history.replace('/auth/login');

        return null;
    }

    return <EnhancedForm clearAndAddHttpError={clearAndAddHttpError} history={history} location={location} {...props} />;
};
